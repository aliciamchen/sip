# LaTeX command names may contain letters only -- no digits -- so the study
# labels ("1a", "3b") become letter tokens ("OneA", "ThreeB"). Derived from the
# registry's number/substudy rather than a hardcoded per-study table.
_NUMBER_WORD = {"1": "One", "2": "Two", "3": "Three"}

# How each inferred latent is named in the paper's prose and table, which is not
# the registry's figure-axis label ("Effort of low-risk share").
_PAPER_TARGET = {"desire": "desire", "intimacy": "relationship", "effort": "physical"}

# Decimals per quantity kind. Per participant (see `_per_participant`) the
# held-out LL quantities run from 0.01 to 10.6, so 2 places carry all of them and
# no reliably nonzero effect displays as 0.00 -- checked across every emitted
# contrast and its CI, including the smallest (Study 2b's reweighting gain, +0.01).
# The two quantities that DO show 0.00 are a true zero (Study 1a's reweighting is
# fitted to exactly zero) and a true null (Study 3a's full - base, whose CI spans
# zero). Any future contrast smaller than 0.005 with an interval excluding zero
# would need a third place back.
DP_LL = 2
DP_PARAM = 2
DP_R = 3
# sigma gets a third place: it is a response-noise scale where the third digit
# is meaningful, and the SI figure caption quotes it to three places.
DP_SIGMA = 3

HEADER = (
    "% !!! AUTO-GENERATED by model/export_results_latex.py -- do not edit by hand.\n"
    "% Regenerate with `make results-latex` after `make model-comparison`.\n"
)


def token(study):
    """Letters-only macro suffix for one study: Study 1a -> "OneA"."""
    return _NUMBER_WORD[study.number] + study.substudy.upper()


def _fmt(value, dp):
    """A number as LaTeX math, so a negative renders as a real minus sign in
    running text as well as in math mode.

    Positives carry no sign: an explicit `+` on differences makes a column of
    improvements read as a column of annotations, and the direction is legible
    from the minus signs alone.
    """
    if value is None or (isinstance(value, float) and not math.isfinite(value)):
        return r"\textit{n/a}"
    return rf"\ensuremath{{{value:.{dp}f}}}"


def _fmt_int(value):
    """An integer with LaTeX's thousands separator (1{,}234)."""
    return f"{value:,}".replace(",", "{,}")


def _per_participant(comparison):
    """Trials per participant, the factor that turns a per-trial held-out LL into
    a per-participant one.

    The paper reports held-out log-likelihood per PARTICIPANT while the
    preregistration specifies per trial. The two differ by exactly this constant,
    so every sign, ordering, and interval-versus-zero conclusion is identical --
    only the scale a reader has to interpret changes, and per trial the smallest
    difference is +0.0048, which reads as nothing. The stored artifacts stay in the
    preregistered unit; the rescale happens here, at the reporting layer, so the
    preregistered quantity is always one division away.

    Whole-number and equal to the scenario count by design: each participant sees
    each scenario exactly once. Asserted rather than assumed, because a study with
    unequal trials per participant would make a single factor wrong for it and the
    error would be a silent constant on every number in the paper.
    """
    n_trials = comparison["n_trials_per_model"]
    n_subj = comparison["n_subjects"]
    factor = n_trials / n_subj
    if abs(factor - round(factor)) > 1e-9:
        raise ValueError(
            f"{n_trials} trials over {n_subj} participants is {factor} trials each, "
            "not a whole number -- a single per-participant factor cannot be right "
            "for this study, so the reported LL scale would be silently wrong."
        )
    return round(factor)


def _fmt_ci(ci, dp=DP_LL):
    """An interval as `[lo, hi]`; unsigned positives, as in `_fmt`."""
    lo, hi = ci
    return rf"\ensuremath{{[{lo:.{dp}f},\ {hi:.{dp}f}]}}"


def _round_half_up(value, dp=0):
    """Round half away from zero, not to even.

    Python's formatting rounds half to even, which turns a genuine 62.5 into
    "62". For a range quoted in prose that reads as an error rather than a
    convention, so the endpoints round the way a reader checking them by hand
    would."""
    scale = 10**dp
    return math.floor(value * scale + 0.5) / scale


def _fmt_range(lo, hi, dp=0):
    """A min--max range as one macro body, e.g. `14--19`.

    Emitted whole rather than as two macros because the prose only ever uses
    these as ranges, and a single token cannot be mis-paired with another
    quantity's endpoint.

    Wrapped in `\\mbox` so the `--` is always typeset in text mode: an en-dash
    dropped inside `$...$` would silently become two minus signs, and the
    exporter cannot see whether a call site is in math mode. The side effect --
    the range will not break across lines -- is what you want for one anyway."""
    body = f"{_fmt(_round_half_up(lo, dp), dp)}--{_fmt(_round_half_up(hi, dp), dp)}"
    return rf"\mbox{{{body}}}"


class Macros:
    """Accumulates `\\newcommand` definitions, refusing duplicates and any name
    that LaTeX would reject."""

    def __init__(self):
        self._items = []
        self._seen = set()

    def add(self, name, body, comment=None):
        if not name.isalpha():
            raise ValueError(
                f"macro name {name!r} is not letters-only -- LaTeX command names "
                "cannot contain digits or underscores"
            )
        if name in self._seen:
            raise ValueError(f"duplicate macro {name!r}")
        self._seen.add(name)
        self._items.append((name, body, comment))

    def render(self):
        defs = [
            (rf"\newcommand{{\{name}}}{{{body}}}", comment)
            for name, body, comment in self._items
        ]
        width = max(len(line) for line, _c in defs)
        return "\n".join(
            f"{line.ljust(width)}  % {comment}" if comment else line
            for line, comment in defs
        )

    def __len__(self):
        return len(self._items)


def load_study(slug):
    """One study's verified comparison statistics and full-model fit."""
    outputs = get_project_root() / "model" / "outputs" / slug
    comparison_path = outputs / "cv_model_comparison.json"
    if not comparison_path.exists():
        raise FileNotFoundError(
            f"{comparison_path} missing -- run `make cv-{slug}` then "
            f"`make model-comparison` before exporting results LaTeX."
        )
    # Refuse to emit numbers from outputs that no longer match their inputs.
    _verify_cv_manifest(slug, outputs)
    verify_fit_manifest(slug, output_dir=outputs)

    comparison = json.loads(comparison_path.read_text())
    preds = json.loads((outputs / "cv_preds_summary.json").read_text())
    fits = json.loads((outputs / "fit_results.json").read_text())
    full_fit = next(r for r in fits if r["model"] == "full")
    primary = {
        e["comparison"].removeprefix("full_minus_"): e for e in comparison["primary"]
    }
    deviation = {e["comparison"]: e for e in comparison.get("prereg_deviation", [])}
    return comparison, preds, full_fit, primary, deviation


#: The run-config tag the preregistered (eta = 0) fit + CV writes under, and the
#: name `compare_configs` gives its comparison against the reported model. Must
#: match `RunConfig.tag()` for `no_reweighting=True`; a mismatch here surfaces as
#: a missing file with this path in the message, not as a silent skip.
PREREG_TAG = "uniform-noreweight"
PREREG_COMPARE_NAME = f"compare_{PREREG_TAG}_vs_reported.json"


def _prereg_deviation_macros(m, tok, slug, reported_ll, *, scale):
    """The preregistered (eta = 0) model's held-out likelihood beside the
    reported model's, and the paired difference between them.

    The reweighting is a deviation from the preregistered specification, so these
    are the numbers that say what the deviation bought. Read from the matched-trial
    comparison rather than from the two configs' own summaries, so the difference
    is paired trial-by-trial and its bootstrap resamples the same participants.

    Returns the comparison entry, for the generated table.
    """
    outputs = get_project_root() / "model" / "outputs" / slug
    path = outputs / "alt" / PREREG_COMPARE_NAME
    if not path.exists():
        raise FileNotFoundError(
            f"{path} missing -- the paper reports the preregistered model beside "
            f"the reported one. Run `bin/prereg-eta0.sh`, then "
            f"`model_comparison.py --study {slug} --compare-configs "
            f"{PREREG_TAG} reported`."
        )
    comparison = json.loads(path.read_text())
    # Both sides' CV must still be the run this comparison was computed from.
    # Each dir's own manifest is self-consistent, so only these hashes can catch
    # one config having been re-run since the comparison.
    for rel, recorded in comparison.get("source", {}).items():
        tag, _, name = rel.partition("/")
        actual = (outputs if tag == "reported" else outputs / "alt" / tag) / name
        if sha256_file(actual) != recorded:
            raise ValueError(
                f"{actual} has changed since {path.name} was computed -- the "
                f"deviation numbers would describe a CV run that no longer "
                f"exists. Re-run `model_comparison.py --study {slug} "
                f"--compare-configs {PREREG_TAG} reported`."
            )
    entry = next((e for e in comparison["per_variant"] if e["variant"] == "full"), None)
    if entry is None:
        raise KeyError(f"{path} has no `full` variant entry")
    # The comparison's own reported-side mean must agree with the one the primary
    # statistics produced; they are computed from the same trials by different
    # code paths, so a disagreement means the two vintages differ.
    # Fixed per-trial tolerance, deliberately NOT tied to DP_LL. DP_LL is a
    # display precision on PER-PARTICIPANT numbers, while both operands here are
    # per trial, so tracking it silently loosened this guard by the scenario
    # count when the reported unit changed. The two sides average the same trials
    # by different code paths and so agree to float noise; anything larger is a
    # vintage difference, which is exactly what this exists to catch.
    if not math.isclose(entry["mean_ll_b"], reported_ll, abs_tol=1e-6):
        raise ValueError(
            f"{slug}: the reported model's mean held-out LL is {reported_ll:.6f} in "
            f"cv_model_comparison.json but {entry['mean_ll_b']:.6f} in {path.name} "
            "-- mixed CV vintages. Re-run `make model-comparison` and the "
            "--compare-configs call."
        )
    m.add(
        f"llPrereg{tok}",
        _fmt(scale * entry["mean_ll_a"], DP_LL),
        "eta = 0 (preregistered) full model, held-out LL per participant",
    )
    _contrast_macros(m, tok, "Reweight", entry, "reported - preregistered", scale=scale)
    return entry


#: Gender categories as recorded in exit_survey.csv, and the macro suffix each
#: gets. `abstain` is a real fourth category -- participants who declined to
#: report -- so female + male + nonconforming does NOT sum to the recruited
#: count, and prose that lists only three will not add up.
_GENDER_SUFFIX = {
    "female": "Female",
    "male": "Male",
    "nonconforming": "Nonconforming",
    "abstain": "Abstain",
}


def _demographics(slug):
    """Recruitment, exclusions and demographics for one study.

    Recruited is every exit-survey row; retained is the distinct participants
    surviving into `main_trials_long.csv`, i.e. the exclusion rule applied by
    `data_prep/json_to_csv.py`.
    """
    import pandas as pd

    root = get_project_root() / "data" / slug
    exit_survey = pd.read_csv(root / "exit_survey.csv")
    retained = pd.read_csv(root / "main_trials_long.csv", usecols=["subject_id"])
    n_recruited = len(exit_survey)
    n_retained = retained["subject_id"].nunique()
    counts = exit_survey["gender"].value_counts()
    unknown = set(counts.index) - set(_GENDER_SUFFIX)
    if unknown:
        raise ValueError(
            f"{slug}: unrecognized gender value(s) {sorted(unknown)} -- add them to "
            "_GENDER_SUFFIX so they get a macro rather than being silently dropped "
            "from the reported breakdown."
        )
    age = exit_survey["age"]
    return {
        # Raw int alongside the formatted macro, for the cross-study totals.
        "_nRecruitedRaw": n_recruited,
        "nRecruited": _fmt_int(n_recruited),
        "nRetained": _fmt_int(n_retained),
        "nExcluded": _fmt_int(n_recruited - n_retained),
        "ageMin": _fmt(age.min(), 0),
        "ageMax": _fmt(age.max(), 0),
        "ageMean": _fmt(age.mean(), 1),
        "ageSd": _fmt(age.std(), 1),
        **{
            f"n{suffix}": _fmt_int(int(counts.get(label, 0)))
            for label, suffix in _GENDER_SUFFIX.items()
        },
    }, n_retained


def _contrast_macros(m, tok, label, entry, note, *, scale):
    """The three macros for one held-out contrast: the point estimate, the CI,
    and a composed "value~[lo, hi]". The composed one is defined by reference to
    the other two, so a number exists in exactly one place."""
    m.add(
        f"dll{label}{tok}",
        _fmt(scale * entry["mean_per_trial_ll_diff"], DP_LL),
        note,
    )
    m.add(f"ci{label}{tok}", _fmt_ci([scale * v for v in entry["ci_95"]]))
    m.add(f"stat{label}{tok}", rf"\dll{label}{tok}~\ci{label}{tok}")


GENERALIZATION_SOURCES = (
    ("transfer", ("model", "outputs", "transfer", "transfer_summary.json")),
    ("pooled", ("model", "outputs", "pooled", "pooled_summary.json")),
)


def _load_generalization():
    """The cross-experiment generalization artifacts, or None if not yet run.

    Absent artifacts are not an error: the analyses are exploratory and a
    checkout that has only run fit/CV should still be able to regenerate every
    other macro. The paper's ``stat`` references are what would then fail to
    resolve, loudly, at LaTeX time.
    """
    out = {}
    for key, parts in GENERALIZATION_SOURCES:
        path = get_project_root().joinpath(*parts)
        if not path.exists():
            return None
        with open(path) as f:
            out[key] = json.load(f)
    return out


def _generalization_macros(m, gen, *, scale):
    """Macros for the all-six pooled-utility contrasts (tab:generalization).

    `scale` turns the stored per-trial numbers into the per-participant unit the
    paper reports, exactly as the primary contrasts do -- these come from the
    same held-out likelihood and must not be quoted in a different unit from the
    numbers beside them. The food-to-nonfood transfer is quoted on the primary
    metric instead (`_generalization_primary_macros`); its held-out-LL contrasts
    are no longer emitted.
    """
    if gen is None:
        return

    def contrast(label, diff, ci, note):
        m.add(f"dll{label}", _fmt(scale * diff, DP_LL), note)
        m.add(f"ci{label}", _fmt_ci([scale * v for v in ci]))
        m.add(f"stat{label}", rf"\dll{label}~\ci{label}")

    # One utility shared across all six.
    pooled = [r for r in gen["pooled"]["rows"] if r["group"] == "all"]
    if pooled:
        for r in pooled:
            contrast(
                "Pool" + token(STUDIES[r["slug"]]),
                r["diff"],
                r["ci_95"],
                f"one shared utility on {r['experiment']}, minus its own fit",
            )
        agg = next(
            (c for c in gen["pooled"].get("combined", []) if c["group"] == "all"),
            None,
        )
        if agg is not None:
            contrast(
                "PoolAll",
                agg["diff"],
                agg["ci_95"],
                "one shared utility, combined over all six experiments",
            )


def build(all_studies):
    m = Macros()
    loaded = {}
    # Constants that must be identical across studies (elicitation runs, CV
    # folds, the scenario count). Collected per study and then checked, so a
    # study that silently diverged is an error rather than whichever value
    # happened to be written last.
    shared = {}
    totals = {"recruited": 0, "retained": 0}

    for study in all_studies:
        slug, tok = study.slug, token(study)
        comparison, preds_rows, full_fit, primary, deviation = load_study(slug)
        loaded[slug] = (comparison, full_fit, primary, deviation)
        # From the model's own cell grid, so the counts describe what was
        # actually fitted rather than a restatement of the intended design.
        n_scenarios = len({r["scenario_label"] for r in preds_rows})
        # K, the temperatures and the LM come from the elicitation manifests --
        # the run that actually produced the tables the fit loaded -- rather than
        # from the pipeline's default constants, which a run can override.
        lm = get_project_root() / "model" / "outputs" / "lm" / slug
        runs_manifest = json.loads((lm / "lm_runs.manifest.json").read_text())
        alts_manifest = json.loads((lm / "lm_alternatives.manifest.json").read_text())
        for key, value in (
            ("nScenarios", n_scenarios),
            ("nRuns", runs_manifest["k_runs"]),
            ("nFolds", n_scenarios),
            # The training-set size the LOSO description states (15 of 16).
            ("nFoldsTrain", n_scenarios - 1),
            ("altTemperature", alts_manifest["gen_temperature"]),
            ("scoreTemperature", runs_manifest["score_temperature"]),
            ("lmName", runs_manifest["model"].split("/")[-1]),
        ):
            shared.setdefault(key, {})[slug] = value

        base_key = reported_base(slug)
        if base_key not in primary:
            raise KeyError(
                f"{slug}: cv_model_comparison.json has no full_minus_{base_key} "
                f"entry, but study_registry.reported_base says the paper reports "
                f"`{base_key}` as Base. Re-run `make cv-{slug} model-comparison`."
            )

        # --- recruitment, exclusions, demographics ---
        demo, n_retained = _demographics(slug)
        if n_retained != comparison["n_subjects"]:
            raise ValueError(
                f"{slug}: {n_retained} participants in main_trials_long.csv but the "
                f"CV outputs were computed on {comparison['n_subjects']}. The paper "
                "would report a sample size the model was not fitted to; re-run "
                f"`make fit-{slug} cv-{slug}` and `make model-comparison`."
            )
        totals["recruited"] += int(demo["_nRecruitedRaw"])
        totals["retained"] += n_retained
        demo.pop("_nRecruitedRaw")
        for i, (key, value) in enumerate(demo.items()):
            m.add(f"{key}{tok}", value, study.paper_label if i == 0 else None)

        # --- the full model's own held-out LL, and the reported contrasts ---
        # Rescaled from the artifacts' preregistered per-trial unit; see
        # `_per_participant` for why the paper reports per participant.
        scale = _per_participant(comparison)
        m.add(
            f"llFull{tok}",
            _fmt(
                scale * comparison["mean_held_out_ll_per_trial"]["full"],
                DP_LL,
            ),
            "held-out LL / participant",
        )
        # The preregistered (eta = 0) model beside it, for the deviation section.
        _prereg_deviation_macros(
            m, tok, slug, comparison["mean_held_out_ll_per_trial"]["full"], scale=scale
        )
        _contrast_macros(
            m, tok, "Base", primary[base_key], f"full - {base_key}", scale=scale
        )
        _contrast_macros(
            m,
            tok,
            "Disc",
            primary["discomfort_only"],
            "full - discomfort_only",
            scale=scale,
        )

        # --- fitted parameters of the reported full model ---
        for field, label in (
            ("param_w_v", "Wv"),
            ("param_w_e", "We"),
            ("param_w_d", "Wd"),
            ("param_gamma", "Gamma"),
            ("alpha_observer", "AlphaObs"),
        ):
            m.add(f"p{label}{tok}", _fmt(full_fit[field], DP_PARAM))
        m.add(f"pSigma{tok}", _fmt(full_fit["param_sigma"], DP_SIGMA))
        # eta exists only for reweighted variants; it is nested at zero, so an
        # absent eta is a fitted zero rather than missing data.
        m.add(f"pEta{tok}", _fmt(full_fit.get("param_eta", 0.0), DP_PARAM))

    # --- the results text's one correlation per study, and its ceiling ---
    _group_correlation_macros(m)

    # --- SI descriptive claims about the elicited comparison sets ---
    _set_diagnostics_macros(m, all_studies)

    # --- the generalization arms on the primary metric (exploratory) ---
    _generalization_primary_macros(m, _load_generalization_primary())

    # Scale comes from `shared`, which has already checked every study agrees on
    # the trials-per-participant factor -- these numbers are quoted beside the
    # primary contrasts and must be in the same unit.
    _generalization_macros(
        m, _load_generalization(), scale=shared["nScenarios"][all_studies[0].slug]
    )

    # Cross-study totals, for the abstract's overall N.
    m.add("nRecruitedTotal", _fmt_int(totals["recruited"]), "all six experiments")
    m.add("nRetainedTotal", _fmt_int(totals["retained"]))

    # One macro per shared constant, but only once every study agrees on it.
    for key, per_study in shared.items():
        distinct = set(per_study.values())
        if len(distinct) > 1:
            raise ValueError(
                f"{key} differs across studies ({per_study}); it is reported as a "
                "single number in the manuscript, so it cannot be emitted as one "
                "macro until they agree."
            )
        value = distinct.pop()
        if isinstance(value, str):
            body = value.replace("_", r"\_")
        elif isinstance(value, int):
            body = _fmt_int(value)
        else:
            body = _fmt(value, 1)
        m.add(key, body, "shared across studies")

    return m, loaded


#: Generalization arm -> macro-name fragment. Keys match
#: `cv/generalization_primary.ARMS`.
_ARM_LABEL = {"own": "OwnFit", "food": "FoodFit", "pooled": "PooledFit"}


def _load_generalization_primary():
    """The generalization arms scored on the primary metric, or None if unrun."""
    path = get_project_root() / "model" / "outputs" / "generalization_primary.json"
    if not path.exists():
        return None
    return json.loads(path.read_text())


def _generalization_primary_macros(m, gen):
    """The nonfood pair's correlation under each generalization arm.

    The main text states the food-to-nonfood result, and states it on the metric
    the paper made primary. Quoting the held-out likelihood there instead would
    put the paper's one main-text use of that metric in the position of carrying
    an equivalence claim, three paragraphs after the Methods explain that it is
    insensitive to the effect these studies test.
    """
    if gen is None:
        return
    for row in gen.get("combined", []):
        if row["group"] != "nonfood":
            continue
        label = _ARM_LABEL[row["arm"]]
        m.add(f"rNonfood{label}", _fmt(row["r"], DP_R))
        m.add(f"ciNonfood{label}", _fmt_ci(row["ci_95"], DP_R))


def generalization_primary_table(gen):
    """tab:generalization-primary (SI): each shared-utility fit on the
    condition-averaged correlation, beside the held-out likelihoods in
    tab:generalization.

    The recovered-gradient columns were dropped from this table; the gradient
    comparison lives in tab:gradients, which is where the model variants are
    compared on it. `generalization_primary.json` still carries
    `grad_median_recovered` for anyone reading the numbers directly.
    """
    by_exp = {}
    for row in gen["per_experiment"]:
        by_exp.setdefault(row["experiment"], {})[row["arm"]] = row
    arms = ("own", "food", "pooled")
    lines = []
    for experiment, rows in by_exp.items():
        cells = [
            _fmt(rows[a]["r"], DP_R) if a in rows else r"\textit{n/a}" for a in arms
        ]
        lines.append(f"{experiment} & " + " & ".join(cells) + r" \\")
    header = (
        r" & \multicolumn{3}{c}{Correlation $r$} \\"
        "\n"
        r"\cmidrule(lr){2-4}"
        "\n"
        r"Experiment & Own & Food & All six \\"
    )
    return _tabular("lccc", header, "\n".join(lines))


def _set_diagnostics_macros(m, all_studies):
    """The SI's descriptive claim about the elicited comparison sets.

    A range over studies rather than one macro per study: the prose quotes it as
    a range, and a range emitted whole cannot be mis-paired or hand-ordered
    backwards, which is what a pair of per-study macros in running text invites.
    The g-contrast and effort-swing ranges this once emitted went with the SI
    prose that quoted them; `set_diagnostics.summarize` still computes them.
    """
    from model.lm import set_diagnostics as sd

    wanted = [s.slug for s in all_studies]
    summary = sd.summarize(wanted)
    missing = [s for s in wanted if s not in summary]
    if missing:
        # Not just "none found": this macro is documented as min--max over
        # STUDIES, so a partially re-elicited state would quietly narrow the
        # range to whichever studies happen to be on disk.
        raise FileNotFoundError(
            f"no outputs/lm/<slug>/lm_runs.jsonl for {missing} -- the SI quotes "
            "this as a range over every study, so a subset would understate "
            "it. Re-run the LM elicitation for those studies."
        )

    medians = [entry["n_alts_median"] for entry in summary.values()]
    m.add(
        "nAltsMedianRange",
        _fmt_range(min(medians), max(medians)),
        "median alternatives per comparison set, min--max over studies",
    )


#: Paper study number -> letters-only macro token, for the pooled correlations
#: (`\rStudyOne`), which are per study number rather than per sub-study.
def _group_token(number):
    return "Study" + _NUMBER_WORD[number]


def _group_correlation_macros(m):
    """The pooled model-vs-human correlation the results text quotes, one per
    study, with the noise ceiling it is judged against.

    Condition grain -- each point averaged over the scenarios -- which is the
    grain the results figures plot. The scenario x condition grain still lives
    in cv_model_comparison.json (`secondary_correlations`); its macros and SI
    table were removed with the manuscript's shortening.

    Only the full model gets macros: the text reports one correlation per study,
    and an ablation's pooled r mixes a DV it can predict with one whose
    prediction is constant, which is a number the figure shows honestly (as a
    vertical stripe) and prose cannot.
    """
    path = get_project_root() / "model" / "outputs" / "group_correlations.json"
    if not path.exists():
        raise FileNotFoundError(
            f"{path} missing -- the results text quotes one pooled correlation "
            "per study. Run `make model-comparison` (it writes this after every "
            "study, since the correlations pool across studies)."
        )
    for entry in json.loads(path.read_text()):
        tok = _group_token(entry["study"])
        # This file is written only by the ALL-studies pass, so re-running one
        # study (`model_comparison.py --study <slug>`, the documented single-study
        # path) refreshes that study's cv_model_comparison.json and leaves this a
        # vintage behind. Every other input here is manifest-verified; this one
        # carries the hashes it was computed from.
        for slug, recorded in entry.get("source", {}).items():
            actual = (
                get_project_root()
                / "model"
                / "outputs"
                / slug
                / "cv_preds_summary.json"
            )
            if sha256_file(actual) != recorded:
                raise ValueError(
                    f"{actual} has changed since {path.name} was computed, so the "
                    f"pooled correlation for Study {entry['study']} describes a CV "
                    f"run that no longer exists. Re-run `make model-comparison` "
                    "(all studies -- the pooled correlations need every one)."
                )
        full = next((c for c in entry["correlations"] if c["model"] == "full"), None)
        if full is None or full["r"] != full["r"]:
            raise ValueError(
                f"Study {entry['study']}: no full-model correlation in {path.name}"
            )
        m.add(
            f"r{tok}",
            _fmt(full["r"], DP_R),
            "pooled over sub-studies and DVs, condition grain",
        )
        m.add(f"ci{tok}", _fmt_ci(full["ci_95"], DP_R))
        ceiling = entry.get("noise_ceiling")
        if ceiling:
            m.add(
                f"ceil{tok}",
                _fmt(ceiling["ceiling"], DP_R),
                "split-half noise ceiling, same grain",
            )


def variance_table(all_studies, loaded):
    """tab:variance-decomposition (SI): where each DV's trial variance lives."""
    lines = []
    for study in all_studies:
        comparison = loaded[study.slug][0]
        for d in comparison.get("variance_decomposition", []):
            if "manipulated_frac_of_total" not in d:
                raise RuntimeError(
                    f"{study.slug}: cv_model_comparison.json predates the "
                    f"action/manipulated variance components. Re-run "
                    f"`make model-comparison` before `make results-latex`."
                )
            lo, hi = d["manipulated_frac_of_total_ci_95"]
            lines.append(
                rf"{study.short_label} & {_PAPER_TARGET[d['dv']]} & "
                rf"{100 * d['frac_explainable']:.0f}\% & "
                rf"{100 * d['manipulated_frac_of_total']:.0f}\% & "
                rf"\ensuremath{{[{100 * lo:.0f},\ {100 * hi:.0f}]}}\% & "
                rf"{100 * d['manipulated_frac_of_explainable']:.0f}\% \\"
            )
    header = (
        r"Study & Inferred & Explainable & Manipulated & 95\% CI & "
        r"Manipulated / explainable \\"
    )
    return _tabular("llrrcr", header, "\n".join(lines))


def _rows(all_studies, cells_for, *, domain_heading=None):
    """Table body rows, one per study.

    `domain_heading` is the column count for a `\\midrule` + italic "Non-food"
    group row before the first non-food study, or None for no heading. It is
    per-table on purpose: tab:model-comparison groups the domains, while
    tab:fitted-params lists all six flat, and regenerating a table should not
    silently restyle it.
    """
    lines, grouped = [], False
    for study in all_studies:
        if domain_heading and study.domain != "food" and not grouped:
            grouped = True
            lines.append(r"\midrule")
            lines.append(
                rf"\multicolumn{{{domain_heading}}}{{l}}{{\itshape Non-food}} \\"
            )
        lines.append(rf"{study.short_label} & {cells_for(study)} \\")
    return "\n".join(lines)


def _tabular(colspec, header, rows):
    """A complete `tabular`, top rule to bottom rule.

    Deliberately the whole environment rather than just the body rows. LaTeX's
    `\\input{...}` appends a `\\relax`, which stops a following `\\bottomrule`
    from being the first token after a row break -- booktabs then fails with
    "Misplaced \\noalign", and a `%` at either end does not fix it. Emitting the
    environment means nothing needing row-break adjacency ever follows the
    `\\input`. The caller keeps the float, \\caption, \\label and \\tabcolsep.
    """
    return "\n".join(
        [
            rf"\begin{{tabular}}{{{colspec}}}",
            r"\toprule",
            header,
            r"\midrule",
            rows,
            r"\bottomrule",
            r"\end{tabular}",
        ]
    )


def model_comparison_table(all_studies):
    """tab:model-comparison: held-out LL per participant, full and vs each ablation.
    `\\statBase*` resolves to the REPORTED base (see reported_base)."""

    def cells(study):
        tok = token(study)
        target = " $+$ ".join(_PAPER_TARGET[dv.name] for dv in study.dvs)
        return f"{target:<26} & " rf"\llFull{tok} & \statBase{tok} & \statDisc{tok}"

    header = "\n".join(
        [
            r" & & \multicolumn{3}{c}{Held-out LL / participant} \\",
            r"\cmidrule(lr){3-5}",
            r"Study & Inferred target & Full & Full $-$ vanilla & "
            r"Full $-$ discomfort-only \\",
        ]
    )
    return _tabular("llccc", header, _rows(all_studies, cells, domain_heading=5))


def fitted_params_table(all_studies):
    """tab:fitted-params: the reported full model's MLE per study."""

    def cells(study):
        tok = token(study)
        return " & ".join(
            rf"\p{p}{tok}"
            for p in ("Wv", "We", "Wd", "Gamma", "AlphaObs", "Sigma", "Eta")
        )

    header = (
        r"Study & $w_v$ & $w_e$ & $w_d$ & $\gamma$ & "
        r"$\alpha_{\mathrm{obs}}$ & $\sigma$ & $\eta$ \\"
    )
    return _tabular("lccccccc", header, _rows(all_studies, cells))


def generalization_table(all_studies):
    """tab:generalization: what a single shared utility costs each experiment.

    Cells are macro references, so this table and any in-text mention of the
    same number cannot drift apart."""
    return _tabular(
        "lr",
        r"Experiment & $\Delta$ held-out log-likelihood per participant \\",
        _rows(
            all_studies,
            lambda study: rf"\statPool{token(study)}",
            domain_heading=2,
        ),
    )


def prereg_deviation_table(all_studies):
    """tab:prereg-deviation: the preregistered (eta = 0) model's held-out
    likelihood beside the reported model's, with the paired difference.

    Carries the fitted eta as its first column, because that is what makes the
    pattern in the difference readable: the reweighting generalizes where eta
    fits large and does not where it fits near zero. Study 1a has no eta -- the
    scope rule grants it no reweighting -- so its two models are the same fit and
    its difference is exactly zero, which the table shows rather than omits."""

    def cells(study):
        tok = token(study)
        return " & ".join(
            (
                rf"\pEta{tok}",
                rf"\llPrereg{tok}",
                rf"\llFull{tok}",
                rf"\statReweight{tok}",
            )
        )

    header = "\n".join(
        [
            r" & & \multicolumn{2}{c}{Held-out LL / participant} & \\",
            r"\cmidrule(lr){3-4}",
            r"Study & $\eta$ & Preregistered & Reported & "
            r"Reported $-$ preregistered \\",
        ]
    )
    return _tabular("lcccc", header, _rows(all_studies, cells, domain_heading=5))


def provenance():
    return (
        f"% git {git_sha()}  generated {datetime.now(timezone.utc).isoformat()}\n"
        f"% Source: model/outputs/<slug>/{{cv_model_comparison,fit_results}}.json\n"
        f"%   and  model/outputs/<slug>/alt/{PREREG_COMPARE_NAME}\n"
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--out-dir",
        type=Path,
        default=get_project_root() / "SIP_journal",
        help="where to write the generated .tex (default: SIP_journal/)",
    )
    ap.add_argument(
        "--print", action="store_true", help="print to stdout and write nothing"
    )
    args = ap.parse_args()

    all_studies = studies()
    m, _loaded = build(all_studies)

    files = {
        "results_macros.tex": (
            HEADER
            + provenance()
            + "%\n"
            + "% LaTeX command names are letters only, so study 1a is OneA, 3b is\n"
            + "% ThreeB. `stat*` composes `dll*` and `ci*` by reference.\n"
            + "%\n"
            + m.render()
            + "\n"
        ),
        "results_table_model_comparison.tex": (
            HEADER + provenance() + model_comparison_table(all_studies) + "\n"
        ),
        "results_table_fitted_params.tex": (
            HEADER + provenance() + fitted_params_table(all_studies) + "\n"
        ),
        "results_table_prereg_deviation.tex": (
            HEADER + provenance() + prereg_deviation_table(all_studies) + "\n"
        ),
        "results_table_variance.tex": (
            HEADER + provenance() + variance_table(all_studies, _loaded) + "\n"
        ),
    }
    # Only when the exploratory generalization analyses have been run -- writing
    # a table of macro references that `build` did not define would turn a
    # not-yet-run analysis into an undefined-control-sequence error.
    if _load_generalization() is not None:
        files["results_table_generalization.tex"] = (
            HEADER + provenance() + generalization_table(all_studies) + "\n"
        )
    gen_primary = _load_generalization_primary()
    if gen_primary is not None:
        files["results_table_generalization_primary.tex"] = (
            HEADER + provenance() + generalization_primary_table(gen_primary) + "\n"
        )

    if args.print:
        for name, text in files.items():
            print(f"\n{'=' * 70}\n{name}\n{'=' * 70}\n{text}")
        return

    if not args.out_dir.is_dir():
        raise SystemExit(
            f"{args.out_dir} not found. The manuscript lives in its own "
            "gitignored repo; pass --out-dir to write elsewhere."
        )
    for name, text in files.items():
        path = args.out_dir / name
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")
    print(f"{len(m)} macros across {len(all_studies)} studies")


if __name__ == "__main__":
    main()
