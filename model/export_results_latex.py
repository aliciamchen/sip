#!/usr/bin/env python3
"""Render the fits and CV results into LaTeX for the manuscript.

Every number the results section states is produced here from the pipeline's
own outputs, so the paper cannot drift from the artifacts. Writes the macros
file plus one file per generated table into `SIP_journal/`:

  results_macros.tex                   one \\newcommand per reported number
  results_table_model_comparison.tex   tab:model-comparison
  results_table_fitted_params.tex      tab:fitted-params
  results_table_prereg_deviation.tex   tab:prereg-deviation
  results_table_variance.tex           tab:variance-decomposition
  results_table_generalization*.tex    tab:generalization / -primary (if run)

Only what the manuscript references is emitted: emitters for the gradient,
scenario-correlation, and design tables went with the manuscript sections that
quoted them. The underlying statistics stay in cv_model_comparison.json;
restore the emitters from git history if a revision brings a section back.

Each table file is a complete `tabular` environment, top rule to bottom rule.
The caller keeps the float, \\caption, \\label and \\tabcolsep, so placement and
spacing stay hand-controlled while the columns and numbers are generated:

    \\begin{table}[t]
      \\centering \\small
      \\input{results_table_model_comparison.tex}
      \\caption{...} \\label{tab:model-comparison}
    \\end{table}

Two invariants this enforces, both of which have bitten before:

- **The reported base.** In the given-relationship studies the paper reports
  `base_shared` as the vanilla model (see `study_registry.reported_base`),
  because the preregistered `base` also swaps the comparison set. The macros read
  that same helper, so the prose, the tables and the figures cannot disagree
  about which model "vanilla" means. The preregistered contrast is emitted
  separately, under `Prereg` names, for the deviation section. Note the variant
  keys on disk stay `base`/`base_shared`; only the reader-facing label is
  "vanilla", which is what the manuscript and the figure columns both say.
- **Provenance.** Both manifests are verified before anything is emitted, so a
  stale or mixed-vintage output set raises instead of quietly producing numbers
  that no longer match the data.

Missing studies are a hard error rather than a skipped macro: a silently absent
macro would surface as an undefined control sequence at LaTeX time, far from the
cause.

Usage:
    uv run python model/export_results_latex.py
    uv run python model/export_results_latex.py --out-dir /tmp/check
    uv run python model/export_results_latex.py --print   # to stdout, write nothing
"""

