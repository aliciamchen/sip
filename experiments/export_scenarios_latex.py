#!/usr/bin/env python3
"""Export the experiment scenarios to LaTeX tables for the paper's Supplementary
Material.

This reads the stimulus CSVs (``scenarios.csv`` for the food studies and
``scenarios_nonfood.csv`` for the non-food studies) and writes one ``longtable``
per set. Each scenario is rendered as a labelled block listing its vignette, the
resource at stake, the two motivational states (low/high desire), the two
physical-effort world states, and the three action descriptions (no-share,
low-risk share, high-risk share) -- i.e. the full stimulus the way the model and
participants encounter it. Re-run it whenever the scenario CSVs change so the
tables in the paper stay in sync with the stimuli.

Two files are written, meant to be ``\\input`` under the "Food scenarios" and
"Nonfood scenarios" subsections of the manuscript:

    si_scenarios_food.tex
    si_scenarios_nonfood.tex

They require ``\\usepackage{longtable}``, ``\\usepackage{booktabs}``, and
``\\usepackage{array}`` in the preamble.

Usage:
    uv run python experiments/export_scenarios_latex.py             # write both files
    uv run python experiments/export_scenarios_latex.py --out-dir somewhere/
"""

import argparse
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT_ROOT = HERE.parent

# Per-scenario fields, in display order: (CSV column, row label). The desire
# states and the two effort world states are the context manipulations, grouped
# together before the three action descriptions.
FIELDS = [
    ("vignette", "Vignette"),
    ("desire_object", "Resource"),
    ("desire_low", "Low-desire state"),
    ("desire_high", "High-desire state"),
    ("low_risk_share_effort_low", "Low-effort world"),
    ("low_risk_share_effort_high", "High-effort world"),
    ("no_share", "Action: don't share"),
    ("low_risk_share", "Action: low-risk share"),
    ("high_risk_share", "Action: high-risk share"),
]

# Single-pass LaTeX escaping. Replacement strings are appended verbatim, so the
# braces/backslashes they contain are never themselves re-escaped.
SPECIAL = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
    "—": "--",
    "–": "--",  # em / en dash -> spaced double-dash
    "‘": "`",
    "’": "'",
    "“": "``",
    "”": "''",
    "…": r"\ldots{}",
    " ": "~",
    "é": r"\'{e}",
    "è": r"\`{e}",
    "á": r"\'{a}",
    "ñ": r"\~{n}",
    "ü": r"\"{u}",
}


def esc(s):
    return "".join(SPECIAL.get(c, c) for c in s)


def nice_label(slug):
    return esc(slug.replace("_", " ").capitalize())


def longtable(rows, is_nonfood):
    L = [
        r"{\small",
        r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.19\textwidth} "
        r">{\raggedright\arraybackslash}p{0.75\textwidth}@{}}",
        r"\toprule",
    ]
    for i, r in enumerate(rows, 1):
        names = f"{esc(r['name_0'])} \\& {esc(r['name_1'])}"
        header = f"\\textbf{{{i}.~{nice_label(r['scenario_label'])}}} \\quad ({names})"
        if is_nonfood:
            header += f" \\hfill \\textit{{{esc(r['scenario_type'])}}}"
        if i > 1:
            L.append(r"\addlinespace[10pt]")
        L.append(
            f"\\multicolumn{{2}}{{@{{}}>{{\\raggedright\\arraybackslash}}"
            f"p{{0.94\\textwidth}}@{{}}}}{{{header}}}\\\\"
        )
        L.append(r"\midrule")
        for col, lab in FIELDS:
            L.append(f"{lab} & {esc(r[col])}\\\\")
    L += [r"\bottomrule", r"\end{longtable}", r"}"]
    return "\n".join(L) + "\n"


HEADER = (
    "% !!! AUTO-GENERATED by experiments/export_scenarios_latex.py -- do not edit by hand.\n"
    "% Regenerate with:  uv run python experiments/export_scenarios_latex.py\n"
    "% Requires \\usepackage{longtable}, \\usepackage{booktabs}, \\usepackage{array}.\n\n"
)


def load(csv_path):
    with open(csv_path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    default_dir = PROJECT_ROOT / "SIP_journal"
    if not default_dir.exists():
        default_dir = PROJECT_ROOT
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=default_dir,
        help=f"output directory (default: {default_dir})",
    )
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    for csv_name, out_name, is_nonfood in (
        ("scenarios.csv", "si_scenarios_food.tex", False),
        ("scenarios_nonfood.csv", "si_scenarios_nonfood.tex", True),
    ):
        rows = load(HERE / csv_name)
        out = args.out_dir / out_name
        out.write_text(HEADER + longtable(rows, is_nonfood), encoding="utf-8")
        print(f"wrote {out}  ({len(rows)} scenarios)")


if __name__ == "__main__":
    main()
